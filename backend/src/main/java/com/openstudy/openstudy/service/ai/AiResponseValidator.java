package com.openstudy.openstudy.service.ai;

import com.openstudy.openstudy.dto.AssignmentEvaluationRequest;
import com.openstudy.openstudy.dto.AssignmentEvaluationResult;
import com.openstudy.openstudy.dto.GeneratedMCQDTO;
import com.openstudy.openstudy.dto.MCQGenerationRequest;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.math.BigDecimal;
import java.math.RoundingMode;
import org.springframework.stereotype.Component;
import org.springframework.util.StringUtils;

@Component
public class AiResponseValidator {

    public static final String SOURCE_GEMINI = "GEMINI";
    public static final String SOURCE_GROQ = "GROQ";
    public static final String SOURCE_MOCK = "MOCK_PLACEHOLDER";
    public static final String STATUS_SUGGESTION = "SUGGESTION_ONLY";
    public static final String STATUS_SCORE_ADJUSTED = "SUGGESTION_SCORE_ADJUSTED";
    public static final String STATUS_MOCK = "MOCK_NOT_LIVE";
    public static final String TEACHER_AUTHORITY_NOTE =
            "AI scores are suggestions only. The teacher retains final grading authority.";

    private static final String DEMO_PREFIX = "[DEMO PLACEHOLDER — not generated by Gemini]";

    public List<GeneratedMCQDTO> validateMcqs(MCQGenerationRequest request, List<GeneratedMCQDTO> generated) {
        AiRequestValidator.validate(request);
        if (generated == null || generated.isEmpty()) {
            throw new AiServiceException(AiErrorCode.EMPTY_RESPONSE, "AI returned no MCQ questions.");
        }
        AiRequestValidator.require(generated.size() == request.getNumberOfQuestions(),
                "AI must return exactly the requested question count.");

        List<GeneratedMCQDTO> validated = new ArrayList<>();
        for (GeneratedMCQDTO question : generated) {
            validated.add(validateSingleMcq(request, question));
        }
        return List.copyOf(validated);
    }

    public GeneratedMCQDTO validateSingleMcq(MCQGenerationRequest request, GeneratedMCQDTO question) {
        AiRequestValidator.validate(request);
        if (question == null || !StringUtils.hasText(question.getQuestionText())) {
            throw new AiServiceException(AiErrorCode.VALIDATION_FAILED, "MCQ is missing question text.");
        }
        AiRequestValidator.text(question.getQuestionText(), "Generated question", 10000, true);
        AiRequestValidator.require(question.getOptions() != null && question.getOptions().size() == 4,
                "MCQ must include exactly four options.");
        for (String option : question.getOptions()) {
            AiRequestValidator.text(option, "MCQ option", 2000, true);
        }
        List<String> options = question.getOptions().stream().map(String::strip).toList();
        AiRequestValidator.require(options.stream().map(value -> value.toUpperCase(Locale.ROOT)).distinct().count() == 4,
                "MCQ options must be distinct.");
        if (!StringUtils.hasText(question.getCorrectOption())) {
            throw new AiServiceException(AiErrorCode.VALIDATION_FAILED, "MCQ is missing a correct option.");
        }
        String canonicalAnswer = options.stream()
                .filter(option -> option.equalsIgnoreCase(question.getCorrectOption().strip()))
                .findFirst().orElse(null);
        if (canonicalAnswer == null) {
            throw new AiServiceException(
                    AiErrorCode.VALIDATION_FAILED,
                    "Correct option is not present in the generated options.");
        }
        String difficulty = AiRequestValidator.difficulty(question.getDifficulty());
        String source = StringUtils.hasText(question.getSource()) ? question.getSource() : SOURCE_GEMINI;
        AiRequestValidator.text(question.getExplanation(), "MCQ explanation", 10000, true);
        String explanation = question.getExplanation().strip();
        return new GeneratedMCQDTO(
                question.getQuestionText().trim(),
                options,
                canonicalAnswer,
                explanation,
                difficulty,
                source);
    }

    public AssignmentEvaluationResult validateEvaluation(
            AssignmentEvaluationRequest request,
            double suggestedScore,
            String feedback,
            List<String> strengths,
            List<String> areasForImprovement,
            String source) {
        AiRequestValidator.validate(request);
        if (!StringUtils.hasText(feedback)) {
            throw new AiServiceException(AiErrorCode.VALIDATION_FAILED, "Evaluation feedback was empty.");
        }
        AiRequestValidator.text(feedback, "Evaluation feedback", 20000, true);
        double maximum = request.getMaximumMarks();
        boolean adjusted = false;
        double score = suggestedScore;
        if (Double.isNaN(score) || Double.isInfinite(score)) {
            throw new AiServiceException(AiErrorCode.VALIDATION_FAILED, "Suggested score is not a valid number.");
        }
        if (score < 0) {
            score = 0;
            adjusted = true;
        }
        if (score > maximum) {
            score = maximum;
            adjusted = true;
        }
        // Round decimal scores without overflow, then cap to the largest two-decimal
        // value within the original maximum (which remains unchanged in the DTO).
        BigDecimal rounded = BigDecimal.valueOf(score).setScale(2, RoundingMode.HALF_UP);
        BigDecimal ceiling = BigDecimal.valueOf(maximum).setScale(2, RoundingMode.DOWN);
        if (rounded.compareTo(ceiling) > 0) {
            rounded = ceiling;
            adjusted = true;
        }
        score = rounded.doubleValue();
        String status = SOURCE_MOCK.equals(source) ? STATUS_MOCK : (adjusted ? STATUS_SCORE_ADJUSTED : STATUS_SUGGESTION);
        return new AssignmentEvaluationResult(
                score,
                maximum,
                feedback.trim(),
                validateFeedbackList(strengths),
                validateFeedbackList(areasForImprovement),
                status,
                source,
                adjusted,
                TEACHER_AUTHORITY_NOTE);
    }

    public String demoPrefix() {
        return DEMO_PREFIX;
    }

    private List<String> validateFeedbackList(List<String> values) {
        AiRequestValidator.require(values != null && values.size() <= 20,
                "Evaluation lists must contain at most 20 entries.");
        for (String value : values) {
            AiRequestValidator.text(value, "Evaluation list entry", 2000, true);
        }
        return values.stream().map(String::strip).toList();
    }

    public String normalizeDifficulty(String generated, String requested) {
        return AiRequestValidator.difficulty(StringUtils.hasText(generated) ? generated : requested);
    }
}

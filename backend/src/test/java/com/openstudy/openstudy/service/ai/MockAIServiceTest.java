package com.openstudy.openstudy.service.ai;

import static org.assertj.core.api.Assertions.assertThat;

import com.openstudy.openstudy.dto.AssignmentEvaluationRequest;
import com.openstudy.openstudy.dto.MCQGenerationRequest;
import org.junit.jupiter.api.Test;

class MockAIServiceTest {

    private final MockAIService service = new MockAIService(new AiResponseValidator());

    @Test
    void mockMcqsAreLabeledAsPlaceholders() {
        MCQGenerationRequest request = new MCQGenerationRequest();
        request.setSubject("Algorithms");
        request.setTopic("Sorting");
        request.setDifficulty("MEDIUM");
        request.setNumberOfQuestions(2);

        var questions = service.generateMCQs(request);

        assertThat(questions).hasSize(2);
        assertThat(questions).allMatch(q -> q.getSource().equals(AiResponseValidator.SOURCE_MOCK));
        assertThat(questions).allMatch(q -> q.getQuestionText().contains("not generated by live AI"));
    }

    @Test
    void mockEvaluationDoesNotClaimLiveProvider() {
        AssignmentEvaluationRequest request = new AssignmentEvaluationRequest();
        request.setQuestionText("Explain polymorphism.");
        request.setStudentAnswer("It is many forms.");
        request.setModelAnswer("Objects sharing an interface can vary in behavior.");
        request.setMaximumMarks(10);

        var result = service.evaluateAssignmentAnswer(request);

        assertThat(result.getSource()).isEqualTo(AiResponseValidator.SOURCE_MOCK);
        assertThat(result.getEvaluationStatus()).isEqualTo(AiResponseValidator.STATUS_MOCK);
        assertThat(result.getFeedback()).contains("No live AI provider was called");
        assertThat(result.getSuggestedScore()).isZero();
    }
}
